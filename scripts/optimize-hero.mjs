import sharp from 'sharp';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const imagesDir = path.join(rootDir, 'public', 'assets', 'images');

const HEROES = [
  {
    key: 'investasi',
    src: path.join(imagesDir, 'hero-investasi-luwu.webp'),
    baseName: 'hero-investasi-luwu',
  },
  {
    key: 'mpp',
    src: path.join(imagesDir, 'hero-mpp-simpurusiang.webp'),
    baseName: 'hero-mpp-simpurusiang',
  },
];

const TARGET_WIDTHS = [480, 768, 1280, 1920];

async function run() {
  console.log('====================================================');
  console.log('🚀 OPTIMIZING HERO IMAGES (AVIF + WEBP + JPG)');
  console.log('====================================================');

  const metadataOutput = {};

  for (const hero of HEROES) {
    if (!fs.existsSync(hero.src)) {
      console.warn(`[WARN] Source file not found: ${hero.src}`);
      continue;
    }

    const originalStats = fs.statSync(hero.src);
    const image = sharp(hero.src);
    const imgMeta = await image.metadata();

    console.log(`\n📸 Processing: ${hero.baseName} (Original: ${(originalStats.size / 1024).toFixed(1)} KB, ${imgMeta.width}x${imgMeta.height})`);

    // 1. Dominant Color & LQIP
    const stats = await image.stats();
    const dominantRgb = stats.dominant;
    const dominantHex = `#${((1 << 24) + (dominantRgb.r << 16) + (dominantRgb.g << 8) + dominantRgb.b).toString(16).slice(1)}`;

    // LQIP: tiny 24px wide blurred WebP (strictly <= 1 KB base64)
    const lqipBuffer = await sharp(hero.src)
      .resize(24, null, { withoutEnlargement: true })
      .webp({ quality: 20 })
      .toBuffer();
    const lqipBase64 = `data:image/webp;base64,${lqipBuffer.toString('base64')}`;
    console.log(`  - Dominant color: ${dominantHex}`);
    console.log(`  - LQIP size: ${lqipBuffer.length} bytes (Base64 length: ${lqipBase64.length})`);

    metadataOutput[hero.key] = {
      dominantColor: dominantHex,
      lqip: lqipBase64,
      aspectRatio: (imgMeta.width && imgMeta.height) ? (imgMeta.width / imgMeta.height).toFixed(4) : '1.7778',
      originalWidth: imgMeta.width || 1280,
      originalHeight: imgMeta.height || 720,
      variants: {}
    };

    // 2. Generate variants for 480, 768, 1280, 1920
    for (const width of TARGET_WIDTHS) {
      metadataOutput[hero.key].variants[width] = {};

      // AVIF
      const avifFileName = `${hero.baseName}-${width}.avif`;
      const avifPath = path.join(imagesDir, avifFileName);
      await sharp(hero.src)
        .resize(width, null, { fit: 'inside', withoutEnlargement: false })
        .avif({ quality: 72, effort: 4 })
        .withMetadata(false)
        .toFile(avifPath);
      const avifSize = fs.statSync(avifPath).size;
      metadataOutput[hero.key].variants[width].avif = {
        path: `/assets/images/${avifFileName}`,
        sizeKB: (avifSize / 1024).toFixed(1)
      };

      // WEBP
      const webpFileName = `${hero.baseName}-${width}.webp`;
      const webpPath = path.join(imagesDir, webpFileName);
      await sharp(hero.src)
        .resize(width, null, { fit: 'inside', withoutEnlargement: false })
        .webp({ quality: 75, effort: 4 })
        .withMetadata(false)
        .toFile(webpPath);
      const webpSize = fs.statSync(webpPath).size;
      metadataOutput[hero.key].variants[width].webp = {
        path: `/assets/images/${webpFileName}`,
        sizeKB: (webpSize / 1024).toFixed(1)
      };

      // JPG Fallback
      const jpgFileName = `${hero.baseName}-${width}.jpg`;
      const jpgPath = path.join(imagesDir, jpgFileName);
      await sharp(hero.src)
        .resize(width, null, { fit: 'inside', withoutEnlargement: false })
        .jpeg({ quality: 75, mozjpeg: true })
        .withMetadata(false)
        .toFile(jpgPath);
      const jpgSize = fs.statSync(jpgPath).size;
      metadataOutput[hero.key].variants[width].jpg = {
        path: `/assets/images/${jpgFileName}`,
        sizeKB: (jpgSize / 1024).toFixed(1)
      };

      console.log(`  ✓ ${width}w -> AVIF: ${(avifSize / 1024).toFixed(1)} KB | WebP: ${(webpSize / 1024).toFixed(1)} KB | JPG: ${(jpgSize / 1024).toFixed(1)} KB`);
    }
  }

  // Generate src/utils/heroImageMetadata.ts
  const tsContent = `/**
 * AUTO-GENERATED BY scripts/optimize-hero.mjs
 * High-performance responsive hero picture & LQIP metadata
 */

export interface HeroVariantInfo {
  path: string;
  sizeKB: string;
}

export interface HeroMetadataItem {
  dominantColor: string;
  lqip: string;
  aspectRatio: number;
  originalWidth: number;
  originalHeight: number;
  avifSrcset: string;
  webpSrcset: string;
  jpgSrcset: string;
  defaultSrc: string;
  sizes: string;
}

export const HERO_METADATA: Record<'investasi' | 'mpp', HeroMetadataItem> = {
  investasi: {
    dominantColor: "${metadataOutput.investasi?.dominantColor || '#071727'}",
    lqip: "${metadataOutput.investasi?.lqip || ''}",
    aspectRatio: ${metadataOutput.investasi?.aspectRatio || 1.775},
    originalWidth: ${metadataOutput.investasi?.originalWidth || 1280},
    originalHeight: ${metadataOutput.investasi?.originalHeight || 721},
    avifSrcset: "/assets/images/hero-investasi-luwu-480.avif 480w, /assets/images/hero-investasi-luwu-768.avif 768w, /assets/images/hero-investasi-luwu-1280.avif 1280w, /assets/images/hero-investasi-luwu-1920.avif 1920w",
    webpSrcset: "/assets/images/hero-investasi-luwu-480.webp 480w, /assets/images/hero-investasi-luwu-768.webp 768w, /assets/images/hero-investasi-luwu-1280.webp 1280w, /assets/images/hero-investasi-luwu-1920.webp 1920w",
    jpgSrcset: "/assets/images/hero-investasi-luwu-480.jpg 480w, /assets/images/hero-investasi-luwu-768.jpg 768w, /assets/images/hero-investasi-luwu-1280.jpg 1280w, /assets/images/hero-investasi-luwu-1920.jpg 1920w",
    defaultSrc: "/assets/images/hero-investasi-luwu-1280.webp",
    sizes: "(max-width: 640px) 100vw, (max-width: 1024px) 90vw, 1280px"
  },
  mpp: {
    dominantColor: "${metadataOutput.mpp?.dominantColor || '#071727'}",
    lqip: "${metadataOutput.mpp?.lqip || ''}",
    aspectRatio: ${metadataOutput.mpp?.aspectRatio || 1.651},
    originalWidth: ${metadataOutput.mpp?.originalWidth || 1280},
    originalHeight: ${metadataOutput.mpp?.originalHeight || 775},
    avifSrcset: "/assets/images/hero-mpp-simpurusiang-480.avif 480w, /assets/images/hero-mpp-simpurusiang-768.avif 768w, /assets/images/hero-mpp-simpurusiang-1280.avif 1280w, /assets/images/hero-mpp-simpurusiang-1920.avif 1920w",
    webpSrcset: "/assets/images/hero-mpp-simpurusiang-480.webp 480w, /assets/images/hero-mpp-simpurusiang-768.webp 768w, /assets/images/hero-mpp-simpurusiang-1280.webp 1280w, /assets/images/hero-mpp-simpurusiang-1920.webp 1920w",
    jpgSrcset: "/assets/images/hero-mpp-simpurusiang-480.jpg 480w, /assets/images/hero-mpp-simpurusiang-768.jpg 768w, /assets/images/hero-mpp-simpurusiang-1280.jpg 1280w, /assets/images/hero-mpp-simpurusiang-1920.jpg 1920w",
    defaultSrc: "/assets/images/hero-mpp-simpurusiang-1280.webp",
    sizes: "(max-width: 640px) 100vw, (max-width: 1024px) 90vw, 1280px"
  }
};
`;

  const tsPath = path.join(rootDir, 'src', 'utils', 'heroImageMetadata.ts');
  fs.writeFileSync(tsPath, tsContent, 'utf8');
  console.log(`\n✅ Generated TypeScript metadata: ${tsPath}`);
  console.log('====================================================\n');
}

run().catch(err => {
  console.error('Fatal error optimizing images:', err);
  process.exit(1);
});
